#!/usr/bin/env bash
# Send a daily Hines Command Center status email.
set -euo pipefail

ROOT="/Backup_Pool/scripts"
STATUS_FILE="${HCC_STATUS_FILE:-$ROOT/hcc-status.json}"
EMAIL_ENV="${HCC_EMAIL_ENV:-$ROOT/hcc-email.env}"
COLLECT_SCRIPT="$ROOT/collect-hcc-status.sh"

if [[ -f "$EMAIL_ENV" ]]; then
	# shellcheck source=/dev/null
	source "$EMAIL_ENV"
fi

: "${HCC_EMAIL_TO:?Missing HCC_EMAIL_TO in $EMAIL_ENV}"
: "${HCC_EMAIL_FROM:?Missing HCC_EMAIL_FROM in $EMAIL_ENV}"
: "${HCC_SMTP_URL:?Missing HCC_SMTP_URL in $EMAIL_ENV}"

if [[ ! -x "$COLLECT_SCRIPT" ]]; then
	echo "Collector script not executable: $COLLECT_SCRIPT" >&2
	exit 1
fi

"$COLLECT_SCRIPT" "$STATUS_FILE"

if [[ ! -s "$STATUS_FILE" ]]; then
	echo "Status file missing or empty: $STATUS_FILE" >&2
	exit 1
fi

hostname="$(jq -r '.hostname // "unknown"' "$STATUS_FILE")"
updated="$(jq -r '.updated // "unknown"' "$STATUS_FILE")"
uptime="$(jq -r '.uptime // "unknown"' "$STATUS_FILE")"
load="$(jq -r '.load // "unknown"' "$STATUS_FILE")"
memory="$(jq -r '.memory // "unknown"' "$STATUS_FILE")"
kernel="$(jq -r '.kernel // "unknown"' "$STATUS_FILE")"
os_name="$(jq -r '.os.name // "Linux"' "$STATUS_FILE")"
patch_pending="$(jq -r '.patches.pending // 0' "$STATUS_FILE")"
patch_security="$(jq -r '.patches.security // 0' "$STATUS_FILE")"

pool_degraded="$(jq '[.storage.pools[]? | select((.health // "UNKNOWN") != "ONLINE")] | length' "$STATUS_FILE")"
network_down="$(jq '[.network[]? | select((.ok // false) == false)] | length' "$STATUS_FILE")"
pve_down="$(jq '[.proxmox[]? | select((.online // false) == false or (.ui_ok // false) == false)] | length' "$STATUS_FILE")"
workloads_stopped="$(jq '[.workloads[]? | select((.status // "") != "running")] | length' "$STATUS_FILE")"
doors_open="$(jq '[.homeassistant.doors[]? | select((.state // "") != "closed")] | length' "$STATUS_FILE")"

summary="OK"
if (( pool_degraded > 0 || network_down > 0 || pve_down > 0 || doors_open > 0 || patch_security > 0 )); then
	summary="ATTENTION"
fi

alerts_file="$(mktemp)"
mail_file="$(mktemp)"
trap 'rm -f "$alerts_file" "$mail_file"' EXIT

{
	jq -r '.storage.pools[]? | select((.health // "UNKNOWN") != "ONLINE") | "Pool \(.name): \(.health)"' "$STATUS_FILE"
	jq -r '.network[]? | select((.ok // false) == false) | "Network down: \(.name) (\(.target))"' "$STATUS_FILE"
	jq -r '.proxmox[]? | select((.online // false) == false or (.ui_ok // false) == false) | "Proxmox issue: \(.name) online=\(.online) ui_ok=\(.ui_ok)"' "$STATUS_FILE"
	jq -r '.homeassistant.doors[]? | select((.state // "") != "closed") | "Door state: \(.name) = \(.state)"' "$STATUS_FILE"
} > "$alerts_file"

subject_prefix="${HCC_EMAIL_SUBJECT_PREFIX:-HCC Daily Report}"
subject="[$summary] ${subject_prefix} - ${hostname}"

{
	printf 'From: %s\n' "$HCC_EMAIL_FROM"
	printf 'To: %s\n' "$HCC_EMAIL_TO"
	printf 'Subject: %s\n' "$subject"
	printf 'Date: %s\n' "$(LC_ALL=C date -R)"
	printf 'MIME-Version: 1.0\n'
	printf 'Content-Type: text/plain; charset=UTF-8\n'
	printf '\n'
	printf 'Hines Command Center Daily Report\n'
	printf '=================================\n\n'
	printf 'Host: %s\n' "$hostname"
	printf 'Updated: %s\n' "$updated"
	printf 'Status: %s\n\n' "$summary"
	printf 'System\n'
	printf -- '------\n'
	printf 'OS: %s\n' "$os_name"
	printf 'Kernel: %s\n' "$kernel"
	printf 'Uptime: %s\n' "$uptime"
	printf 'Load: %s\n' "$load"
	printf 'Memory: %s\n\n' "$memory"
	printf 'Counts\n'
	printf -- '------\n'
	printf 'Patches pending: %s (security: %s)\n' "$patch_pending" "$patch_security"
	printf 'Pools degraded: %s\n' "$pool_degraded"
	printf 'Network targets down: %s\n' "$network_down"
	printf 'Proxmox nodes with issues: %s\n' "$pve_down"
	printf 'Stopped workloads: %s\n' "$workloads_stopped"
	printf 'Doors not closed: %s\n\n' "$doors_open"
	printf 'Alerts\n'
	printf -- '------\n'
	if [[ -s "$alerts_file" ]]; then
		cat "$alerts_file"
	else
		printf 'No active alerts.\n'
	fi
	printf '\n'
	printf 'Generated by: %s\n' "$0"
} > "$mail_file"

if [[ "${HCC_EMAIL_DRY_RUN:-0}" == "1" ]]; then
	cat "$mail_file"
	exit 0
fi

curl_args=(
	--silent
	--show-error
	--fail
	--url "$HCC_SMTP_URL"
	--mail-from "$HCC_EMAIL_FROM"
	--upload-file "$mail_file"
)

if [[ "${HCC_SMTP_STARTTLS:-1}" == "1" ]]; then
	curl_args+=(--ssl-reqd)
fi

if [[ -n "${HCC_SMTP_USER:-}" || -n "${HCC_SMTP_PASS:-}" ]]; then
	curl_args+=(--user "${HCC_SMTP_USER:-}:${HCC_SMTP_PASS:-}")
fi

IFS=',' read -r -a rcpts <<< "$HCC_EMAIL_TO"
for rcpt in "${rcpts[@]}"; do
	trimmed="$(xargs <<< "$rcpt")"
	[[ -n "$trimmed" ]] && curl_args+=(--mail-rcpt "$trimmed")
done

curl "${curl_args[@]}"
